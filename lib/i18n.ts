function allValues(entry: TranslationEntry) {
  return [entry.fr, entry.en, entry.de, ...(entry.aliases || [])]
}

function preserveOuterWhitespace(original: string, translated: string) {
  const prefix = original.match(/^\s*/)?.[0] || ''
  const suffix = original.match(/\s*$/)?.[0] || ''
  return `${prefix}${translated}${suffix}`
}

export function translatePhrase(value: string, language: Language) {
  const compact = value.replace(/\s+/g, ' ').trim()
  if (!compact) return value

  const entry = TRANSLATIONS.find((item) => allValues(item).includes(compact))
  if (!entry) return value

  return preserveOuterWhitespace(value, entry[language])
}
